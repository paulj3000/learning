/**
 * Adventure scaffold generator: pure string templates, no file system. The CLI
 * (`scripts/game-engine/scaffold-adventure.ts`) reads argv and writes the files; this module
 * decides what they contain, so it is unit tested without touching disk.
 *
 * Generated placeholders are valid ids and localisation keys, never child-facing copy. Every
 * placeholder carries a `TODO` so an unfinished scaffold is easy to find.
 */

import type { ValidationIssue } from '../core/errors';

/**
 * The package name generated modules import. Built from parts so this file's source text holds
 * no import-shaped reference to the engine itself (the LAI-ENG-002 workspace check scans text).
 */
export const ENGINE_PACKAGE = ['@lai', 'game-engine'].join('/');

export const SCAFFOLD_ID = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

export interface ScaffoldInput {
  realmId: string;
  adventureId: string;
  /** Enable the jump capability with a jump challenge AND its required accessible route. */
  jump?: boolean;
  /** ISO date (YYYY-MM-DD) for the spec's "Last reviewed" line. */
  today?: string;
  /** Contents of docs/adventures/templates/adventure-specification.md; a built-in stub otherwise. */
  specTemplate?: string;
}

export interface ScaffoldFile {
  /** Relative to the output directory. */
  path: string;
  content: string;
}

export interface ScaffoldResult {
  ok: boolean;
  issues: ValidationIssue[];
  /** Default output directory, relative to the repo root. */
  defaultOutDir: string;
  files: ScaffoldFile[];
}

export function defaultScaffoldDir(realmId: string, adventureId: string): string {
  return `react/src/features/adventures/definitions/${realmId}/${adventureId}`;
}

export function toCamelCase(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());
}

export function toTitleCase(id: string): string {
  return id
    .split('-')
    .map((word) => (word ? word[0]!.toUpperCase() + word.slice(1) : word))
    .join(' ');
}

function definitionSource({ realmId, adventureId, jump }: Required<Pick<ScaffoldInput, 'realmId' | 'adventureId'>> & { jump: boolean }): string {
  const name = toCamelCase(adventureId);
  const area = `${adventureId}-area`;
  const jumpBlocks = jump
    ? `
  // Jumping is a capability, not a category. Required progress never depends on it, so every
  // jump challenge names an accessible route that needs no jumping.
  jumpChallenges: [
    {
      id: '${adventureId}-jump-1',
      areaId: '${area}',
      jumpRouteId: '${adventureId}-jump-1-jump-route',
      accessibleRouteId: '${adventureId}-jump-1-walk-route',
      optional: true, // Sprouts: jump routes are optional only
    },
  ],
  checkpoints: [{ id: '${adventureId}-checkpoint-1', areaId: '${area}' }],`
    : `
  jumpChallenges: [],
  checkpoints: [],`;
  return `/**
 * Adventure definition: ${adventureId} (realm ${realmId}). Generated by scaffold-adventure.
 * Replace every TODO. The specification next to this file is the source of truth; follow
 * docs/adventures/adventure-standard.md. Content ids only: no child-facing copy lives here.
 */

import { defineAdventure } from '${ENGINE_PACKAGE}';

export const ${name}Adventure = defineAdventure({
  id: '${adventureId}',
  realmId: '${realmId}',
  version: '0.1.0',
  engineApi: '^0.1.0',
  ageBands: ['SPROUT', 'PATHFINDER', 'EXPLORER'],
  learningObjectiveIds: ['${adventureId}.objective.todo'],
  areas: ['${area}'],
  capabilities: [${jump ? "{ id: 'movement.jump' }" : ''}],
  movementProfiles: {},
  difficultyProfiles: {},
  components: [],
  questIds: [],
  challengeIds: [],${jumpBlocks}
  // Pillar 2: learning changes the island. Name the visible WorldChange this adventure leaves.
  worldConsequenceId: '${adventureId}.consequence.todo',
  contentSource: 'MANIFEST',
  requiredServices: [],
});
`;
}

function testSource({ adventureId }: { adventureId: string }): string {
  const name = toCamelCase(adventureId);
  return `import { describe, expect, it } from 'vitest';
import { createCapabilityRegistry, validateAdventure, validationOk } from '${ENGINE_PACKAGE}';
import { ${name}Adventure } from './${adventureId}.definition';

// A stub registry that accepts the requested capabilities so this test checks the definition's
// own structure. Swap it for the engine's real capability registry once the adventure's
// capabilities are configured (TODO).
function stubRegistry() {
  const registry = createCapabilityRegistry();
  for (const { id } of ${name}Adventure.capabilities) {
    registry.register({
      id,
      version: '0.1.0',
      description: 'test stub',
      defaults: {},
      validate: (value) => validationOk(value ?? {}),
    });
  }
  return registry;
}

describe('${adventureId} adventure definition', () => {
  it('is a valid adventure definition', () => {
    const result = validateAdventure(${name}Adventure, stubRegistry());
    expect(result.issues).toEqual([]);
    expect(result.ok).toBe(true);
  });

  it('gives every jump challenge a distinct accessible route', () => {
    for (const challenge of ${name}Adventure.jumpChallenges) {
      expect(challenge.accessibleRouteId).toBeTruthy();
      expect(challenge.accessibleRouteId).not.toBe(challenge.jumpRouteId);
    }
  });

  it('declares a world consequence', () => {
    expect(${name}Adventure.worldConsequenceId).toBeTruthy();
  });
});
`;
}

const BUILT_IN_SPEC = `# Adventure Specification: \`<adventure name>\`

- **Status:** Draft
- **Last reviewed:** <date>

> Built-in stub: the template docs/adventures/templates/adventure-specification.md was not
> supplied. Copy the template and complete every section.

## 1. Identity

| Field | Value |
|---|---|
| Adventure title (child-facing) | TODO |
| Adventure template id (sent with every AI request) | <adventure id> |

## 2. Realm and Place

| Field | Value |
|---|---|
| Realm (Island, \`catalog.World\`) | <realm id> |
`;

function specSource(input: Required<Pick<ScaffoldInput, 'realmId' | 'adventureId' | 'today'>> & { jump: boolean; specTemplate?: string }): string {
  let spec = input.specTemplate ?? BUILT_IN_SPEC;
  const title = toTitleCase(input.adventureId);
  spec = spec
    .replace('`<adventure name>`', `\`${title}\``)
    .replace('`<Draft | In review | Owner approved>`', 'Draft')
    .replace('`<YYYY-MM-DD>`', input.today)
    .replace('<date>', input.today)
    .replace('`<template id>`', `\`${input.adventureId}\``)
    .replace('<adventure id>', input.adventureId)
    .replace('<realm id>', input.realmId)
    .replace('`<island slug>`', `\`${input.realmId}\``);
  const note = `<!-- Scaffolded for adventure "${input.adventureId}" in realm "${input.realmId}"${
    input.jump ? ' with the jump capability (accessible routes required)' : ''
  }. Companion files: ${input.adventureId}.definition.ts and ${input.adventureId}.definition.test.ts. -->\n\n`;
  return note + spec;
}

/** Generates the scaffold files. Pure; validates ids and reports problems as issues. */
export function scaffoldAdventure(input: ScaffoldInput): ScaffoldResult {
  const issues: ValidationIssue[] = [];
  for (const [key, value] of [
    ['realmId', input.realmId],
    ['adventureId', input.adventureId],
  ] as const) {
    if (typeof value !== 'string' || !SCAFFOLD_ID.test(value) || value.length > 64) {
      issues.push({ path: key, message: 'must be lowercase kebab-case (letters, digits, single hyphens), at most 64 characters' });
    }
  }
  const defaultOutDir = SCAFFOLD_ID.test(String(input.realmId)) && SCAFFOLD_ID.test(String(input.adventureId))
    ? defaultScaffoldDir(input.realmId, input.adventureId)
    : '';
  if (issues.length > 0) {
    return { ok: false, issues, defaultOutDir, files: [] };
  }
  const jump = input.jump === true;
  const today = input.today ?? new Date().toISOString().slice(0, 10);
  return {
    ok: true,
    issues,
    defaultOutDir,
    files: [
      { path: `${input.adventureId}.definition.ts`, content: definitionSource({ realmId: input.realmId, adventureId: input.adventureId, jump }) },
      { path: `${input.adventureId}.spec.md`, content: specSource({ ...input, jump, today }) },
      { path: `${input.adventureId}.definition.test.ts`, content: testSource({ adventureId: input.adventureId }) },
    ],
  };
}
